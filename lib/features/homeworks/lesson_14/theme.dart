import 'package:flutter/material.dart';

TextStyle semiBoldTextStyle(double fontSize) => TextStyle(
      fontFamily: 'SilpoText',
      fontWeight: FontWeight.w600,
      fontSize: fontSize,
    );

TextStyle regularTextStyle(double fontSize) => TextStyle(
      fontFamily: 'SilpoText',
      fontWeight: FontWeight.w400,
      fontSize: fontSize,
    );
